# Function to categorize the educational level
def categorize_educational_level(level_id):
    if level_id in {14, 15, 16, 17, 18, 19, 20, 21, 22}:
        return 1, 'زیر دیپلم'
    elif level_id == 13:
        return 2, 'دیپلم'
    elif level_id in {4, 5, 6}:
        return 3, 'فوق دیپلم'
    elif level_id in {9, 10, 11, 12}:
        return 4, 'لیسانس'
    elif level_id in {7, 8}:
        return 5, 'فوق لیسانس'
    elif level_id in {2, 3}:
        return 6, 'دکتری'
    elif level_id == 0:
        return 7, 'نامشخص'
    else:
        return 7, 'نامشخص'


